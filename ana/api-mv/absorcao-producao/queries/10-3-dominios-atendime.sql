-- 10-3: dominios reais das colunas de tipo, sistema e sinais em ATENDIME
-- Bloco 10: nucleo assistencial
-- Saida: 10-3-dominios-atendime.csv (camada commitavel, resultados/)
-- Responde: C6-2 (TP_ATENDIMENTO, recorte do eletivo), C6-5 (CD_SISTEMA),
--   sinais de obito e internacao, insights 8 e 12
SELECT 'TP_ATENDIMENTO' AS dimensao, TP_ATENDIMENTO AS valor, COUNT(*) AS qtd
FROM   DBAMV.ATENDIME GROUP BY TP_ATENDIMENTO
UNION ALL
SELECT 'CD_SISTEMA', TO_CHAR(CD_SISTEMA), COUNT(*)
FROM   DBAMV.ATENDIME GROUP BY CD_SISTEMA
UNION ALL
SELECT 'SN_OBITO', SN_OBITO, COUNT(*)
FROM   DBAMV.ATENDIME GROUP BY SN_OBITO
UNION ALL
SELECT 'SN_INTERNADO', SN_INTERNADO, COUNT(*)
FROM   DBAMV.ATENDIME GROUP BY SN_INTERNADO
UNION ALL
SELECT 'SN_RETORNO', SN_RETORNO, COUNT(*)
FROM   DBAMV.ATENDIME GROUP BY SN_RETORNO
UNION ALL
SELECT 'CD_TIPO_INTERNACAO', TO_CHAR(CD_TIPO_INTERNACAO), COUNT(*)
FROM   DBAMV.ATENDIME GROUP BY CD_TIPO_INTERNACAO
ORDER BY 1, 3 DESC;
