SELECT 'TP_SITUACAO' AS dimensao, TP_SITUACAO AS valor, COUNT(*) AS qtd
FROM   DBAMV.IT_AGENDA_CENTRAL GROUP BY TP_SITUACAO
UNION ALL
SELECT 'TP_FORMA_AGENDAMENTO', TP_FORMA_AGENDAMENTO, COUNT(*)
FROM   DBAMV.IT_AGENDA_CENTRAL GROUP BY TP_FORMA_AGENDAMENTO
UNION ALL
SELECT 'TP_VISUALIZACAO', TP_VISUALIZACAO, COUNT(*)
FROM   DBAMV.IT_AGENDA_CENTRAL GROUP BY TP_VISUALIZACAO
UNION ALL
SELECT 'TP_PRESENCA_FALTA', TP_PRESENCA_FALTA, COUNT(*)
FROM   DBAMV.IT_AGENDA_CENTRAL GROUP BY TP_PRESENCA_FALTA
UNION ALL
SELECT 'SN_ENCAIXE', SN_ENCAIXE, COUNT(*)
FROM   DBAMV.IT_AGENDA_CENTRAL GROUP BY SN_ENCAIXE
ORDER BY 1, 3 DESC;
